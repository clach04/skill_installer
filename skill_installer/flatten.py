"""Render resolved skills as a single portable markdown document."""

from __future__ import annotations

import sys
from pathlib import Path

from .resolver import Resolution, resolve  # noqa: F401  (Resolution re-exported)
from .scanner import Skill, _parse_frontmatter, scan_source

_INDENT = " " * 4

DEFAULT_PREAMBLE = """\
This document was generated by `skill_installer flatten`. It packages the \
skills listed below for use in a session that has no skill-loading \
mechanism. Read each skill's instructions and follow them as if the skill \
had been loaded into you.

- Each skill is a `## <skill-name>` section with a metadata line (bucket, \
description), followed by that skill's files.
- File content is indented by four spaces; each file is introduced by a \
bold label.
- Skills listed after the ones you named were pulled in automatically as \
dependencies.
- Where a skill tells you to call another skill by name, read the \
corresponding `## <name>` section instead."""


def _read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return None


def _indent(text: str) -> str:
    return "\n".join(_INDENT + line if line.strip() else "" for line in text.splitlines())


def _longest_backtick_run(text: str) -> int:
    longest = current = 0
    for ch in text:
        if ch == "`":
            current += 1
            longest = max(longest, current)
        else:
            current = 0
    return longest


def _render_block(text: str, rel: str, use_fences: bool) -> str:
    text = text.strip("\n")
    if use_fences:
        run = _longest_backtick_run(text)
        ticks = "`" * max(3, run + 1)
        if run >= 3:
            print(
                f"warning: {rel} contains a {run}-backtick run; "
                f"wrapping in {len(ticks)} backticks",
                file=sys.stderr,
            )
        return f"{ticks}\n{text.rstrip()}\n{ticks}"
    return _indent(text.rstrip())


def _skill_files(skill: Skill, all_files: bool) -> list[tuple[str, Path]]:
    """(label, path) for each file to inline for this skill, in order."""
    skill_md = skill.dir / "SKILL.md"
    entries: list[tuple[str, Path]] = []
    seen: set[Path] = set()

    def add(path: Path) -> None:
        if path in seen:
            return
        seen.add(path)
        try:
            rel = path.relative_to(skill.dir)
        except ValueError:  # linked file outside the skill's own dir
            rel = path
        entries.append((str(rel).replace("\\", "/"), path))

    add(skill_md)
    for path in sorted(skill.requires_file):
        add(path)
    if all_files:
        for path in sorted(skill.dir.rglob("*")):
            if path.is_file():
                add(path)
    return entries


def _render_skill(skill: Skill, all_files: bool, use_fences: bool) -> str:
    lines: list[str] = [f"## {skill.name}", ""]
    bucket = skill.bucket or "root"
    meta = f"_{bucket}" + (f" — {skill.description}_" if skill.description else "_")
    lines += [meta, ""]

    for label, path in _skill_files(skill, all_files):
        text = _read_text(path)
        if text is None:
            print(f"warning: skipping non-text file: {label}", file=sys.stderr)
            continue
        if path == skill.dir / "SKILL.md":
            _, text = _parse_frontmatter(text)
        lines += [f"**{label}**", "", _render_block(text, label, use_fences), ""]
    return "\n".join(lines).rstrip()


def flatten(
    selected: list[str],
    source: Path,
    all_files: bool = False,
    use_fences: bool = False,
    no_deps: bool = False,
    preamble: str | None = DEFAULT_PREAMBLE,
) -> str:
    """Return the full flattened markdown document. `preamble` may be None
    to emit none."""
    catalog = scan_source(source)

    if no_deps:
        resolution = Resolution()
        for name in selected:
            if name not in catalog:
                raise KeyError(f"unknown skill: {name}")
            skill = catalog[name]
            resolution.skills[name] = skill
            resolution.log.append(f"selected {name} ({skill.bucket or 'root'})")
    else:
        resolution = resolve(selected, catalog)

    for line in resolution.log:
        print(line, file=sys.stderr)  # stderr: keep stdout as the document only

    parts: list[str] = []
    if preamble is not None:
        parts.append(preamble)
    for name, skill in resolution.skills.items():
        parts.append(_render_skill(skill, all_files, use_fences))
    return "\n\n".join(parts) + "\n"
